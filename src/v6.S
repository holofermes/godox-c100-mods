@ Webcam fixes (docs/webcam.md), not part of the canary build. None runs at
@ boot: the aspect gate runs on a left/right press, the record gate on a
@ record start, v6_size when a host starts the stream, and v6_cfg is read
@ only by the USB code in webcam mode. They call no C, so they live in the
@ RAM gap and work whether or not the overlay loaded. Linked last in the gap:
@ the stubs, the loader and st keep the canary's addresses.
@
@ Blocked = the host streams: EP5 alt at 0x123d3c, stored by 0x3e5e0, 3 while
@ streaming, 0 when closed.

	.equ	VS_ALT, 0x123d3c

@ Z clear when blocked. Clobbers ip and the flags.
	.macro	BLOCKED
	ldr	ip, =VS_ALT
	ldr	ip, [ip]
	cmp	ip, #0
	.endm

@ Aspect step 0x213e0, from the BL at its three callers (photo 0x2ec48, video
@ 0x37104 and 0x37134). Blocked, the index at 0x1217bd stays put, the caller
@ finds it equal to the stored setting and skips the mode re-entry that
@ stops the webcam encoder. r0 is the step; the callers ignore it after.
	.global	v6_aspect_gate
	.type	v6_aspect_gate, %function
v6_aspect_gate:
	BLOCKED
	bxne	lr
	b	0x213e0

@ Record start, from the BEQ at 0x35898 in the record start/stop function
@ 0x35860. Blocked, 0x3589c returns 0 with no state change; else on to the
@ start at 0x35a10, which needs r3 (the record flags) and r5 as they are.
	.global	v6_rec_gate
	.type	v6_rec_gate, %function
v6_rec_gate:
	BLOCKED
	bne	0x3589c
	b	0x35a10

	.ltorg

@ ---- frame sizes ----
@
@ The host picks a frame descriptor by bFrameIndex in PROBE/COMMIT. The
@ SET_CUR handler 0x52644 copies the host's struct to 0xe3b2c before it checks
@ it, and the probe patch in tools/patch.py lets indexes 0..6 through. On
@ stream start (alt 3, msg 0x8007) sensor_on(0x106) builds the geometry in
@ 0xf004; for APMode 0x106 it copies the target, 1920x1080, into the second
@ path at 0xf510. v6_size replaces that copy with the committed frame's size,
@ and the 0xf4e0 patch sets the display size from the second path, as stock
@ APMode 0x107 does at 0xf320. Path 0 and the clip stay 1920x1080, so every
@ size is the full sensor scaled down.

	.equ	PROBE_FRAME, 0xe3b2c + 3 @ bFrameIndex of the last SET_CUR
	@ per-path zoom bytes, paths 0 and 1; 0x12d68 sets both to 100 on Photo
	@ and Video entry only, and below 100 a small output is a centre crop
	.equ	ZOOM_A, 0xf19f4
	.equ	ZOOM_B, 0xf19c0
	.equ	NFRAMES, 6

@ From the BL at 0xf510 (APMode 0x106 in 0xf004). Returns r0 = W, r3 = H of
@ the committed frame; index 0 or above NFRAMES gives frame 1. Uses r0, r3
@ and ip only: r1 and r2 carry the values 0xf2d8 prints. 0xf514 is a nop;
@ 0xf518..0xf524 store r0 and r3 into the second path.
	.global	v6_size
	.type	v6_size, %function
v6_size:
	ldr	ip, =ZOOM_A
	mov	r0, #100
	orr	r0, r0, r0, lsl #8
	strh	r0, [ip]
	ldr	ip, =ZOOM_B
	strh	r0, [ip]
	ldr	ip, =PROBE_FRAME
	ldrb	ip, [ip]
	sub	ip, ip, #1
	cmp	ip, #NFRAMES - 1
	movhi	ip, #0
	adr	r0, v6_sizes
	add	ip, r0, ip, lsl #2
	ldrh	r0, [ip]
	ldrh	r3, [ip, #2]
	bx	lr

@ W, H per bFrameIndex 1..NFRAMES, all 16:9 like the sensor; the same sizes
@ as the frame descriptors below
	.global	v6_sizes
	.type	v6_sizes, %object
v6_sizes:
	.2byte	1920, 1080
	.2byte	1280, 720
	.2byte	640, 360
	.2byte	320, 180
	.2byte	256, 144
	.2byte	128, 72

	.ltorg

